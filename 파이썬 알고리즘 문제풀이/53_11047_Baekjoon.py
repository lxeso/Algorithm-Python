# 백준 11047번 동전 0 - 그리디
'''
문제 조건
준규는 N종류의 동전을 매우 많이 가지고 있으며, 
이 동전들을 적절히 사용해 가치의 합이 K가 되도록 만들고자 합니다. 
필요한 동전 개수의 최솟값을 구하세요.


'''

'''
알고리즘
1. 입력받기
동전의 종류 N과 목표 가치 K를 입력받음.
동전의 가치를 저장하는 리스트를 입력받아 오름차순으로 정렬된 상태로 저장.
2. 큰 동전부터 사용하기
그리디 알고리즘을 사용해 가치가 가장 큰 동전부터 목표 가치 K를 채움.
동전의 개수는 K를 동전의 가치로 나눈 몫으로 계산.
남은 값은 나머지(K %= 동전 가치)로 업데이트.
3. 최소 동전 개수 합산
각 동전 가치에 대해 필요한 동전 개수를 합산.
4. 결과 출력
모든 동전 계산이 끝나면 필요한 동전의 최소 개수를 출력.
'''

# 입력받기
N, K = map(int, input().strip().split())
coins = [int(input().strip()) for _ in range(N)]

# 큰 동전부터 탐색
coins.reverse()  # 내림차순 정렬
count = 0  # 필요한 동전 개수

for coin in coins:
    if K == 0:
        break
    count += K // coin  # 동전의 개수
    K %= coin  # 남은 금액

# 결과 출력
print(count)
