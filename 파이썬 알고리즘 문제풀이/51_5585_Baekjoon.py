# 백준 5585번 거스름돈 - 그리디

''' 
문제 정의 1000엔 지폐를 내고 물건 값을 계산한 뒤, 잔돈을 500엔, 100엔, 50엔, 10엔, 5엔, 1엔 단위로 거슬러 줄 때 최소 동전 개수를 계산하는 프로그램 작성. 
[입력] 한 줄에 지불할 금액(1 이상 1000 미만의 정수)이 주어짐. 
[출력] 잔돈에 포함된 동전의 최소 개수를 출력. '''

''' 
알고리즘

입력받은 금액을 지불할 돈으로 설정하고, 거스름돈은 1000엔에서 지불한 돈을 뺀 값으로 계산.
거스름돈을 500, 100, 50, 10, 5, 1 순서대로 나누어 각 동전의 개수를 계산.
각 동전의 개수를 합산해 최소 동전 개수를 출력. 
'''


# 입력받기
payment = int(input().strip())  # 지불할 금액 입력받기

# 잔돈 계산
change = 1000 - payment

# 동전 단위 정의
coins = [500, 100, 50, 10, 5, 1]

# 최소 동전 개수 초기화
count = 0

# 큰 단위 동전부터 차례로 탐색
for coin in coins:
    count += change // coin  # 해당 동전으로 거슬러 줄 개수
    change %= coin  # 남은 잔돈 계산

# 결과 출력
print(count)
