''' 
문제 정의 
주어진 거스름돈을 쿼터(Quarter, $0.25), 다임(Dime, $0.10), 니켈(Nickel, $0.05), 페니(Penny, $0.01)로 최소 개수의 동전을 사용해 거슬러주는 프로그램 작성. 
[입력] 첫째 줄에 테스트 케이스의 개수 T가 주어짐. 둘째 줄부터 각 테스트 케이스마다 거스름돈 C를 나타내는 정수 (단위: 센트, 1 ≤ C ≤ 500) 제공. 
[출력] 각 테스트 케이스마다 필요한 쿼터, 다임, 니켈, 페니의 개수를 공백으로 구분해 출력. 
'''


'''
알고리즘
1. 테스트 케이스 개수 T를 입력받음.
2. T만큼 반복하며, 거스름돈 C를 입력받음.
3. 거스름돈 C를 쿼터, 다임, 니켈, 페니 순서대로 나누어 각 동전의 개수를 계산. 
3-1. C를 각 동전의 가치로 나눈 몫은 해당 동전의 개수. 3-2. C는 해당 동전 가치로 나눈 나머지로 업데이트.
4. 계산된 각 동전의 개수를 출력.
'''
# 코드 구현
T = int(input().strip())  # 테스트 케이스 수 입력

for _ in range(T):
    C = int(input().strip())  # 거스름돈 입력
    quarters = C // 25  # 쿼터 개수
    C %= 25  # 나머지 계산
    dimes = C // 10  # 다임 개수
    C %= 10  # 나머지 계산
    nickels = C // 5  # 니켈 개수
    C %= 5  # 나머지 계산
    pennies = C  # 남은 값은 페니
    print(quarters, dimes, nickels, pennies)
