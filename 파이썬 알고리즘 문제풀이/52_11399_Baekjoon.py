# 백준 11399번 ATM - 그리디

'''
문제

ATM 앞에 사람들이 줄을 서서 돈을 인출합니다. 
각 사람이 돈을 인출하는 데 걸리는 시간이 주어졌을 때, 각 사람이 기다리는 시간의 합을 최소화해야 합니다. 줄을 서는 순서를 최적화하여 최소 시간을 구하세요.
'''

'''
알고리즘
1. 입력받기
사람 수 N과 각 사람이 돈을 인출하는 데 걸리는 시간 리스트 P를 입력받음.
2. 시간 정렬
각 사람이 기다리는 시간의 합을 최소화하려면 인출 시간이 작은 순서대로 줄을 세워야 함.
따라서 리스트 P를 오름차순으로 정렬.
3. 누적 합 계산
정렬된 리스트를 기준으로 각 사람이 대기하는 시간을 누적하여 합산.
4. 누적 대기 시간 = 현재 사람까지의 누적 합.
결과 출력
총 대기 시간의 최소합을 출력.
'''

# 입력받기
N = int(input().strip())  # 사람 수
P = list(map(int, input().strip().split()))  # 각 사람이 인출하는 데 걸리는 시간

# 오름차순 정렬
P.sort()

# 누적 합 계산
total_time = 0
current_sum = 0
for time in P:
    current_sum += time  # 현재 사람의 대기 시간 추가
    total_time += current_sum  # 누적 대기 시간 합산

# 결과 출력
print(total_time)
