'''
문제 분석
주어진 여학생 N명과 남학생 M명 중 K명을 인턴으로 보내야 할 때, 2명의 여학생과 1명의 남학생으로 구성된 팀의 최대 개수를 구하는 프로그램 작성.  
[입력] 첫째 줄에 N, M, K가 주어짐 (0 ≤ M ≤ 100, 0 ≤ N ≤ 100, 0 ≤ K ≤ M+N).  
[출력] 만들 수 있는 팀의 최대 개수를 출력.  
'''

'''
알고리즘
1. 여학생 N명과 남학생 M명을 입력받음.
2. 전체 학생 중 K명을 인턴으로 보내야 하므로, 인턴을 고려한 인원을 계산.
K명을 보내는 최적 조건: 여학생과 남학생의 비율을 유지하면서 최대 팀이 가능하도록 여학생을 더 많이 줄임.
3. 팀 구성 조건:
한 팀은 2명의 여학생과 1명의 남학생으로 구성.
최대 팀의 수는 (N // 2)와 M 중 최소값.
4. K명을 인턴으로 보낸 후의 팀 계산:
(N // 2, M)에서 K명을 차감하며 팀의 수를 조정.
5. 최적화된 팀의 개수를 계산 후 출력.
'''

N, M, K = map(int, input().strip().split())  # 여학생, 남학생, 인턴 수 입력

# 인턴으로 보낼 인원을 반영해 팀 계산
while K > 0:
    if N >= 2 * M:  # 여학생이 많으면 여학생 우선 줄임
        N -= 1
    else:  # 남학생이 많거나 동수라면 남학생 줄임
        M -= 1
    K -= 1

# 최대 팀 수 계산
max_teams = min(N // 2, M)
print(max_teams)
